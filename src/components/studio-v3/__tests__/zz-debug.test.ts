import { it } from "vitest";
import { findTour } from "@/data/signatureTours";
import { isStopClosedOn } from "@/data/stopOperational";
import { judgeFinalDayTime } from "@/lib/studio-v3/finalTimeGate";
import { certifyFrozenDayFromPickup, frozenDayAllowsCheckout } from "@/lib/studio-v3/pickupDoorToDoor";
import { rebuildLiveCommercialAuthority } from "@/lib/studio-v3/liveCommercialAuthority";
import { pickupOriginCoord, resolveStudioV3Route } from "../curation";
import { resolveAuthoritativeRouteStops, studioRouteShapingInput } from "../studioRouteAuthority";
import { INITIAL_STATE } from "../types";
it("dbg", () => {
  const id="arrabida-wine-allinclusive";
  const state:any={...INITIAL_STATE,feeling:"wine-food",companions:"couple",interests:["wine","gastronomy"],rhythm:"full",dateExact:"2026-10-27",dateMode:"exact",pickup:"lisbon",adults:2,guests:2};
  const tour=findTour(id)!;
  const resolved=resolveStudioV3Route({...studioRouteShapingInput(state),eligibleTourIds:[id],preferTourId:id});
  const all=resolveAuthoritativeRouteStops({resolved,catalogStops:tour.stops,anchorTourId:id});
  const points=all.filter(p=>!isStopClosedOn(p.label,state.dateExact));
  console.log(resolved.skeletonTourKey, all.map(p=>[p.label,p.blueprintStopId,p.inventoryStopId,p.durationMinutes]));
  console.log("time",JSON.stringify(judgeFinalDayTime({points,skeletonTourId:id,rhythm:state.rhythm})).slice(0,400));
  console.log("d2d",frozenDayAllowsCheckout(certifyFrozenDayFromPickup({points,pickupCoord:pickupOriginCoord(state.pickup),rhythm:state.rhythm})));
  console.log("comm",JSON.stringify(rebuildLiveCommercialAuthority({anchorTourId:id,moments:points,edited:true})).slice(0,600));
});
