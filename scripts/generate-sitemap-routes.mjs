#!/usr/bin/env node
/**
 * Generates `src/generated/sitemap-routes.ts` — the automatic list of static,
 * indexable, HTTP-200 EN routes that `/sitemap.xml` emits.
 *
 * A route is included when ALL of these hold:
 *   - it is a real page route under `src/routes/*.tsx` (no `$param`, no splat)
 *   - it does not `throw redirect(...)` (sitemaps list final destinations only)
 *   - its `head()` does not declare `robots: noindex`
 *   - it is not an internal/utility surface (see EXCLUDED_PREFIXES / EXCLUDED_PATHS)
 *
 * Dynamic collections (Signature tours, Local Stories, journal posts, PT twins)
 * stay owned by the sitemap route itself — they come from data, not the file tree.
 *
 * Run: node scripts/generate-sitemap-routes.mjs [--check]
 *   --check exits 1 when the committed file is stale (used in CI).
 */
import fs from "node:fs";
import path from "node:path";

const ROUTES_DIR = path.resolve("src/routes");
const OUT_FILE = path.resolve("src/generated/sitemap-routes.ts");

/** Internal, auth-gated, QA or machine surfaces — never indexable. */
const EXCLUDED_PREFIXES = [
  "/.",
  "/api",
  "/admin",
  "/lovable",
  "/e2e",
  "/qa",
  "/functions",
  "/email",
  "/pt", // PT twins come from PT_PAIRED_PATHS
  "/tours", // Signature tours come from signatureTours
  "/local-stories/", // articles come from LOCAL_STORIES_ARTICLES + journal_posts
  "/checkout",
];

/** One-off exclusions: token pages, previews, post-conversion and utility routes. */
const EXCLUDED_PATHS = new Set([
  "/sitemap.xml",
  "/auth",
  "/mcp",
  "/mcp-signin",
  "/booking-confirmed",
  "/booking-receipt",
  "/itinerary",
  "/unsubscribe",
  "/builder",
  "/brand-qa",
  "/hero-verify",
  "/preview-check",
  "/typography-audit",
  "/studio-drift",
  "/studio-living-atlas-preview",
  "/search", // thin, query-driven results surface
]);

/** Crawl-priority overrides. Anything absent uses the default below. */
const OVERRIDES = {
  "/": { changefreq: "weekly", priority: "1.0" },
  "/experiences": { changefreq: "weekly", priority: "0.9" },
  "/studio-v3": { changefreq: "weekly", priority: "0.9" },
  "/multi-day": { changefreq: "weekly", priority: "0.9" },
  "/portugal-tours": { changefreq: "monthly", priority: "0.9" },
  "/day-tours": { changefreq: "weekly", priority: "0.8" },
  "/local-stories": { changefreq: "weekly", priority: "0.7" },
  "/portugal-travel-designer": { changefreq: "monthly", priority: "0.85" },
  "/luxury-tours-portugal": { changefreq: "monthly", priority: "0.85" },
  "/private-tours-portugal": { changefreq: "monthly", priority: "0.85" },
  "/itineraries/10-day-private-portugal-tour": { changefreq: "monthly", priority: "0.8" },
  "/proposal-in-portugal": { changefreq: "monthly", priority: "0.8" },
  "/corporate": { changefreq: "monthly", priority: "0.7" },
  "/trade": { changefreq: "monthly", priority: "0.7" },
  "/about": { changefreq: "monthly", priority: "0.6" },
  "/contact": { changefreq: "monthly", priority: "0.6" },
  "/press": { changefreq: "monthly", priority: "0.5" },
  "/reviews": { changefreq: "monthly", priority: "0.5" },
  "/terms": { changefreq: "yearly", priority: "0.4" },
  "/privacy": { changefreq: "yearly", priority: "0.4" },
  "/cookies": { changefreq: "yearly", priority: "0.4" },
};

const DEFAULT = { changefreq: "monthly", priority: "0.7" };

function walk(dir, out = []) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) walk(full, out);
    else if (entry.name.endsWith(".tsx")) out.push(full);
  }
  return out;
}

const rows = [];
for (const file of walk(ROUTES_DIR)) {
  const source = fs.readFileSync(file, "utf8");
  const m = /createFileRoute\(\s*["'`]([^"'`]+)["'`]\s*\)/.exec(source);
  if (!m) continue;
  const routePath = m[1];
  if (routePath.includes("$") || routePath.includes("_")) continue;
  if (EXCLUDED_PATHS.has(routePath)) continue;
  if (routePath !== "/" && EXCLUDED_PREFIXES.some((p) => routePath.startsWith(p))) continue;
  if (/throw\s+redirect\s*\(/.test(source)) continue;
  if (/content\s*:\s*["'`][^"'`]*noindex/.test(source)) continue;
  rows.push({ path: routePath, ...(OVERRIDES[routePath] ?? DEFAULT) });
}

rows.sort((a, b) => a.path.localeCompare(b.path));

const body = `// AUTO-GENERATED by scripts/generate-sitemap-routes.mjs — do not edit by hand.
// Run \`bun run sitemap:generate\` after adding, removing or redirecting a route.
export interface SitemapRoute {
  path: string;
  changefreq: "always" | "hourly" | "daily" | "weekly" | "monthly" | "yearly" | "never";
  priority: string;
}

export const SITEMAP_STATIC_ROUTES: SitemapRoute[] = [
${rows
  .map(
    (r) =>
      `  { path: ${JSON.stringify(r.path)}, changefreq: ${JSON.stringify(r.changefreq)}, priority: ${JSON.stringify(r.priority)} },`,
  )
  .join("\n")}
];
`;

const check = process.argv.includes("--check");
const current = fs.existsSync(OUT_FILE) ? fs.readFileSync(OUT_FILE, "utf8") : "";

if (check) {
  if (current !== body) {
    console.error(
      "\n✖ src/generated/sitemap-routes.ts is stale. Run `bun run sitemap:generate` and commit the result.\n",
    );
    process.exit(1);
  }
  console.log(`✔ sitemap routes up to date — ${rows.length} static entries.`);
} else {
  fs.mkdirSync(path.dirname(OUT_FILE), { recursive: true });
  fs.writeFileSync(OUT_FILE, body);
  console.log(`✔ wrote ${rows.length} static sitemap routes to src/generated/sitemap-routes.ts`);
}
